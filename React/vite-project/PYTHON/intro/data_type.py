# Example variables
x = 10              # Integer
y = 3.14             # Float
z = "Hello"          # String
a = True             # Boolean<True, False>
b = [1, 2, 3]        # List
c = {1, 2, 3}        # Set
d = (1, 2, 3)        # Tuple
e = {"key": "value"} # Dictionary <object>
 # for dict we use the bracket notation

 # Determining the types
print(type(x))  # Output: <class 'int'>
print(type(y))  # Output: <class 'float'>
print(type(z))  # Output: <class 'str'>
print(type(a))  # Output: <class 'bool'>
print(type(b))  # Output: <class 'list'>
print(type(c))  # Output: <class 'set'>
print(type(d))  # Output: <class 'tuple'>
print(type(e))  # Output: <class 'dict'>